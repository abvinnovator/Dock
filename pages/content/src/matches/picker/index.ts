const h = <K extends keyof HTMLElementTagNameMap>(tag: K, className?: string, text?: string) => {
  const el = document.createElement(tag);
  if (className) el.className = className;
  if (text) el.textContent = text;
  return el;
};

const run = async () => {
  // Re-injecting replaces an overlay that's already open.
  pickerWindow.__dockPickerAbort?.abort();
  document.getElementById(HOST_ID)?.remove();
  const abort = new AbortController();
  pickerWindow.__dockPickerAbort = abort;
  const listen = { capture: true, signal: abort.signal };

  const session: PickSessionInfo = await chrome.runtime
    .sendMessage({ type: 'GET_PICK_SESSION' })
    .catch(() => ({ text: '' }));

  const host = document.createElement('div');
  host.id = HOST_ID;
  host.style.cssText = 'all: initial; position: fixed; inset: 0; z-index: 2147483647; pointer-events: none;';
  const root = host.attachShadow({ mode: 'open' });
  const style = h('style');
  style.textContent = STYLES;
  root.appendChild(style);

  const box = h('div', 'box');
  const boxTag = h('span', 'tag');
  box.appendChild(boxTag);

  const canvasApp = detectCanvasApp();
  const bar = h('div', 'bar');
  const barText = h('span', 'bar-text');
  if (canvasApp) {
    barText.append(canvasApp.instruction);
  } else if (session.destinationName) {
    barText.append('Click the new field for ', h('b', '', `“${session.destinationName}”`));
  } else {
    barText.append('Click the field Dock should ', h('b', '', 'ship into'));
  }
  const cancelBtn = h('button', 'ghost', 'Cancel');
  bar.append(h('span', 'logo', 'Dock.'), barText, cancelBtn);

  const panel = h('div', 'panel');
  root.append(box, bar, panel);
  document.documentElement.appendChild(host);

  let picked: HTMLElement | null = null;
  let pickedField: FieldSpec | null = null;
  let hovered: HTMLElement | null = null;
  let hoveredOk = false;
  let mode: PlaceMode = 'newline';

  const close = () => {
    abort.abort();
    host.remove();
    if (pickerWindow.__dockPickerAbort === abort) pickerWindow.__dockPickerAbort = undefined;
  };

  const cancel = () => {
    close();
    chrome.runtime.sendMessage({ type: 'PICKER_CANCEL' }).catch(() => {});
  };

  const placeBox = () => {
    const target = picked ?? hovered;
    if (!target || !target.isConnected) {
      box.style.display = 'none';
      return;
    }
    const r = target.getBoundingClientRect();
    box.style.display = 'block';
    box.style.left = `${r.left - 3}px`;
    box.style.top = `${r.top - 3}px`;
    box.style.width = `${r.width + 6}px`;
    box.style.height = `${r.height + 6}px`;
    box.className = `box ${picked ? 'picked' : hoveredOk ? 'hover' : 'bad'}`;
    boxTag.textContent = picked
      ? 'Selected'
      : hoveredOk
        ? labelOf(target) || 'Ship here'
        : 'Not a text field — pick an input or text box';
  };

  const save = () => {
    const field = canvasApp?.tag === 'gsheets' ? selectedSheetCell() : pickedField;
    if (!field) {
      const hint = panel.querySelector<HTMLElement>('.cell-hint');
      if (hint) hint.textContent = 'Click a single cell in the sheet first.';
      return;
    }
    const nameInput = panel.querySelector<HTMLInputElement>('input.name');
    const fallbackName = field.column ? `Column ${field.column}` : field.label;
    const name = clean(nameInput?.value, 60) || fallbackName || `Field on ${location.hostname.replace(/^www\./, '')}`;
    close();
    chrome.runtime.sendMessage({ type: 'PICKER_DONE', field, name, mode }).catch(() => {});
  };

  const showPanel = (target: { field: FieldSpec; modes: ModeOption[]; description: string; defaultName: string }) => {
    const { modes } = target;
    pickedField = target.field;
    if (!modes.some(m => m.mode === mode)) mode = modes[0].mode;

    panel.replaceChildren();
    panel.style.display = 'block';
    panel.append(
      h('h2', '', session.destinationName ? 'Update the field' : 'Ship here?'),
      h('p', 'muted', target.description),
    );

    const nameLabel = h('label', 'field-label', 'Name it');
    const nameInput = h('input', 'name');
    nameInput.placeholder = 'e.g. SO ID, Candidate name, Notes';
    nameInput.value = session.destinationName ?? target.defaultName;
    panel.append(nameLabel, nameInput);

    panel.append(h('label', 'field-label', 'When you ship'));
    const modeList = h('div', 'modes');
    for (const option of modes) {
      const btn = h('button', `mode${option.mode === mode ? ' on' : ''}`, option.label);
      btn.type = 'button';
      btn.addEventListener('click', () => {
        mode = option.mode;
        modeList.querySelectorAll('.mode').forEach(b => b.classList.toggle('on', b === btn));
      });
      modeList.appendChild(btn);
    }
    panel.appendChild(modeList);

    if (session.text) {
      panel.append(h('label', 'field-label', 'Shipping now'), h('div', 'cargo', session.text));
    }

    const row = h('div', 'row');
    const saveBtn = h('button', 'primary', session.text ? 'Save & ship' : 'Save field');
    saveBtn.append(' ', h('kbd', '', 'Enter'));
    const backBtn = h('button', 'ghost', 'Cancel');
    saveBtn.addEventListener('click', save);
    backBtn.addEventListener('click', cancel);
    row.append(saveBtn, backBtn);
    panel.appendChild(row);

    // In Docs and Sheets the user still has to click into the page, so don't grab focus.
    if (!canvasApp) {
      nameInput.focus();
      nameInput.select();
    }
  };

  const showFieldPanel = (el: HTMLElement) =>
    showPanel({
      field: describeField(el),
      modes: modesFor(el),
      description: `Field: ${labelOf(el) || el.tagName.toLowerCase()} · click another field to change`,
      defaultName: labelOf(el),
    });

  const isOurs = (e: Event) => e.composedPath().includes(host);

  cancelBtn.addEventListener('click', cancel);

  if (canvasApp) {
    showPanel({
      field: {
        selector: `@${canvasApp.tag}`,
        tag: canvasApp.tag,
        label: canvasApp.tag === 'gdocs' ? 'cursor' : 'column',
      },
      modes: canvasApp.modes,
      description: canvasApp.description,
      defaultName: canvasApp.defaultName,
    });

    // Show which cell is selected, so the user sees the column Dock will fill.
    if (canvasApp.tag === 'gsheets') {
      const hint = h('div', 'cargo cell-hint');
      panel.querySelector('.muted')?.after(hint);
      const update = () => {
        const cell = selectedSheetCell();
        hint.textContent = cell
          ? `Selected: ${cell.column}${cell.row} → fills column ${cell.column}, starting at row ${cell.row}`
          : 'Click a cell in the sheet…';
      };
      update();
      const timer = setInterval(update, 300);
      abort.signal.addEventListener('abort', () => clearInterval(timer));
    }
    window.addEventListener(
      'keydown',
      e => {
        if (!isOurs(e)) return;
        if (e.key === 'Escape') cancel();
        else if (e.key === 'Enter') save();
        e.stopImmediatePropagation();
      },
      listen,
    );
    return;
  }

  // Keep the page from reacting to clicks while the user is choosing a field.
  for (const type of ['pointerdown', 'mousedown', 'mouseup', 'pointerup', 'dblclick'] as const) {
    window.addEventListener(
      type,
      e => {
        if (isOurs(e)) return;
        e.preventDefault();
        e.stopImmediatePropagation();
      },
      listen,
    );
  }

  window.addEventListener(
    'mousemove',
    e => {
      if (isOurs(e)) return;
      const target = e.target instanceof HTMLElement ? e.target : null;
      const editable = editableFrom(target);
      hovered = editable ?? target;
      hoveredOk = !!editable;
      if (!picked) placeBox();
    },
    listen,
  );

  window.addEventListener(
    'click',
    e => {
      if (isOurs(e)) return;
      e.preventDefault();
      e.stopImmediatePropagation();
      const editable = editableFrom(e.target);
      if (!editable) return;
      picked = editable;
      placeBox();
      showFieldPanel(editable);
    },
    listen,
  );

  window.addEventListener(
    'keydown',
    e => {
      if (e.key === 'Escape') {
        e.preventDefault();
        e.stopImmediatePropagation();
        cancel();
      } else if (e.key === 'Enter' && picked && isOurs(e)) {
        e.preventDefault();
        save();
      }
      // Typing in our name box shouldn't trigger the page's shortcuts.
      if (isOurs(e)) e.stopImmediatePropagation();
    },
    listen,
  );

  window.addEventListener('scroll', placeBox, { ...listen, passive: true });
  window.addEventListener('resize', placeBox, listen);
};

run();
