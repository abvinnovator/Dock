/**
 * Dock - field picker overlay.
 * Injected on demand (chrome.scripting) into the page the user wants to ship text
 * to. The user clicks the field, names it, chooses how text is placed, and the
 * result goes back to the background as PICKER_DONE.
 */

type PlaceMode = 'replace' | 'newline' | 'comma' | 'space';

interface FieldSpec {
  selector: string;
  tag: string;
  name?: string;
  placeholder?: string;
  ariaLabel?: string;
  label?: string;
  // Google Sheets: the column this destination fills, the row it started at, and
  // the sheet tab it's on.
  column?: string;
  row?: number;
  sheet?: string;
}

interface PickSessionInfo {
  text: string;
  destinationName?: string;
}

const HOST_ID = 'dock-field-picker';

// Lets a second injection close the overlay a first one left open.
const pickerWindow = window as Window & { __dockPickerAbort?: AbortController };

// ─── Field Detection ──────────────────────────────────────────────────────────

const TEXT_INPUT_TYPES = new Set(['', 'text', 'search', 'email', 'url', 'tel', 'number']);

// Returns the text field the user meant: the element itself, the input behind a
// <label>, or the outermost element of a rich-text editor.
const editableFrom = (node: EventTarget | null): HTMLElement | null => {
  if (!(node instanceof HTMLElement)) return null;
  if (node instanceof HTMLTextAreaElement) return node;
  if (node instanceof HTMLInputElement) return TEXT_INPUT_TYPES.has(node.type) ? node : null;
  if (node instanceof HTMLLabelElement) return editableFrom(node.control);
  if (node.isContentEditable) {
    let el = node;
    while (el.parentElement?.isContentEditable) el = el.parentElement;
    return el;
  }
  return null;
};

const clean = (value: string | null | undefined, max = 48) => {
  const text = (value ?? '').replace(/\s+/g, ' ').trim();
  return text.length > max ? `${text.slice(0, max - 1)}…` : text;
};

const labelOf = (el: HTMLElement): string => {
  const labelledBy = el.getAttribute('aria-labelledby');
  const labelledText = labelledBy
    ? labelledBy
        .split(/\s+/)
        .map(id => document.getElementById(id)?.textContent ?? '')
        .join(' ')
    : '';
  const ownLabel = 'labels' in el ? (el as HTMLInputElement).labels?.[0]?.textContent : '';
  return (
    clean(el.getAttribute('aria-label')) ||
    clean(labelledText) ||
    clean(ownLabel) ||
    clean(el.getAttribute('placeholder')) ||
    clean(el.getAttribute('data-placeholder')) ||
    clean(el.getAttribute('title')) ||
    clean(el.getAttribute('name'))
  );
};

const escapeAttr = (value: string) => value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

const isUnique = (selector: string) => {
  try {
    return document.querySelectorAll(selector).length === 1;
  } catch {
    return false;
  }
};

// Ids generated by frameworks (":r1:", "input-8231") change between page loads.
const isStableId = (id: string) => !!id && !/[:]|\d{3,}/.test(id);

const selectorFor = (el: HTMLElement): string => {
  const tag = el.tagName.toLowerCase();
  if (isStableId(el.id) && isUnique(`#${CSS.escape(el.id)}`)) return `#${CSS.escape(el.id)}`;

  for (const attr of ['name', 'aria-label', 'placeholder', 'data-testid', 'data-test-id', 'data-qa', 'title']) {
    const value = el.getAttribute(attr);
    const selector = value ? `${tag}[${attr}="${escapeAttr(value)}"]` : '';
    if (selector && isUnique(selector)) return selector;
  }

  // Fall back to a path from the nearest ancestor with a stable id.
  const parts: string[] = [];
  let node: HTMLElement | null = el;
  while (node && node !== document.body && node !== document.documentElement) {
    if (node !== el && isStableId(node.id) && isUnique(`#${CSS.escape(node.id)}`)) {
      parts.unshift(`#${CSS.escape(node.id)}`);
      break;
    }
    const nodeTag = node.tagName.toLowerCase();
    const siblings = node.parentElement
      ? Array.from(node.parentElement.children).filter(c => c.tagName === node!.tagName)
      : [];
    parts.unshift(siblings.length > 1 ? `${nodeTag}:nth-of-type(${siblings.indexOf(node) + 1})` : nodeTag);
    node = node.parentElement;
  }
  return parts.join(' > ');
};

const describeField = (el: HTMLElement): FieldSpec => ({
  selector: selectorFor(el),
  tag: el.tagName.toLowerCase(),
  name: el.getAttribute('name') ?? undefined,
  placeholder: el.getAttribute('placeholder') ?? undefined,
  ariaLabel: el.getAttribute('aria-label') ?? undefined,
  label: labelOf(el) || undefined,
});

type ModeOption = { mode: PlaceMode; label: string };

// Google Docs and Sheets draw their content on a canvas, so there's no field to
// click: Dock ships to the document's cursor, or down a column of cells.
interface CanvasApp {
  tag: 'gdocs' | 'gsheets';
  instruction: string;
  description: string;
  defaultName: string;
  modes: ModeOption[];
}

const detectCanvasApp = (): CanvasApp | null => {
  if (location.hostname !== 'docs.google.com') return null;
  if (location.pathname.startsWith('/document/')) {
    return {
      tag: 'gdocs',
      instruction: 'Click in the document where shipped text should go, then save.',
      description: 'Google Docs · Dock types at your cursor and keeps going from there',
      defaultName: document.title.replace(/ - Google Docs$/, ''),
      modes: [
        { mode: 'newline', label: 'One per line' },
        { mode: 'comma', label: 'Followed by a comma' },
        { mode: 'space', label: 'Followed by a space' },
      ],
    };
  }
  if (location.pathname.startsWith('/spreadsheets/')) {
    return {
      tag: 'gsheets',
      instruction: 'Click the cell where the next item goes (e.g. under your “Job ID” header), then save.',
      description: 'Google Sheets · this column fills row by row, in step with your other columns on this sheet',
      defaultName: '',
      modes: [
        { mode: 'newline', label: 'Next empty cell down' },
        { mode: 'replace', label: 'Always the selected cell' },
      ],
    };
  }
  return null;
};

// The cell selected in Google Sheets, read from the name box (e.g. "B2").
const selectedSheetCell = (): FieldSpec | null => {
  const ref = (document.querySelector<HTMLInputElement>('#t-name-box')?.value ?? '')
    .split(':')[0]
    .replace(/\$/g, '')
    .toUpperCase();
  const match = /^([A-Z]+)(\d+)$/.exec(ref);
  if (!match) return null;
  const sheet = clean(document.querySelector('.docs-sheet-active-tab .docs-sheet-tab-name')?.textContent) || undefined;
  return {
    selector: '@gsheets',
    tag: 'gsheets',
    column: match[1],
    row: Number(match[2]),
    sheet,
    label: `column ${match[1]}`,
  };
};

const modesFor = (el: HTMLElement): ModeOption[] => {
  const multiline = el instanceof HTMLTextAreaElement || el.isContentEditable;
  return [
    ...(multiline ? [{ mode: 'newline' as const, label: 'Add on a new line' }] : []),
    { mode: 'replace', label: 'Replace what’s there' },
    { mode: 'comma', label: 'Add after a comma' },
    ...(multiline ? [] : [{ mode: 'space' as const, label: 'Add after a space' }]),
  ];
};

